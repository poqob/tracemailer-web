    /**
     * Detect browser language with fallback to Turkish/English
     */
    function detectBrowserLanguage() {
        try {
            var languages = navigator.languages || [navigator.language || navigator.userLanguage || ''];
            for (var i = 0; i < languages.length; i++) {
                var l = (languages[i] || '').toLowerCase();
                if (l.indexOf('tr') === 0) return 'tr';
                if (l.indexOf('en') === 0) return 'en';
            }
        } catch (e) {
            // ignore
        }
        var primary = ((navigator.language || navigator.userLanguage || '').toLowerCase());
        if (primary.indexOf('tr') === 0) return 'tr';
        return 'en'; // Default fallback for international visitors
    }

    /**
     * Get saved language preference from localStorage ('auto', 'tr', 'en')
     */
    function getSavedPreference() {
        try {
            var saved = localStorage.getItem(STORAGE_KEY);
            if (saved === 'tr' || saved === 'en' || saved === 'auto') {
                return saved;
            }
            return 'auto';
        } catch (e) {
            return 'auto';
        }
    }

    /**
     * Resolve effective language code based on preference
     */
    function resolveEffectiveLanguage(preference) {
        if (preference === 'tr' || preference === 'en') {
            return preference;
        }
        return detectBrowserLanguage();
    }

    var currentPreference = getSavedPreference();
    var currentLanguage = resolveEffectiveLanguage(currentPreference);

    /**
     * Look up translation key in current dictionary with dot-notation
     */
    function translate(key, params) {
        if (!key) return '';
        var dict = dictionaries[currentLanguage] || dictionaries['tr'];
        var parts = key.split('.');
        var val = dict;

        for (var i = 0; i < parts.length; i++) {
            if (val && typeof val === 'object' && parts[i] in val) {
                val = val[parts[i]];
            } else {
                val = null;
                break;
            }
        }

        // Fallback to Turkish if missing in target language
        if (val === null && currentLanguage !== 'tr') {
            var fallbackDict = dictionaries['tr'];
            val = fallbackDict;
            for (var j = 0; j < parts.length; j++) {
                if (val && typeof val === 'object' && parts[j] in val) {
                    val = val[parts[j]];
                } else {
                    val = null;
                    break;
                }
            }
        }

        if (typeof val !== 'string') {
            if (key === 'landing.nav.blog' || key === 'landing.footer.blog') {
                return (currentLanguage === 'en') ? 'Guides & Blog' : 'Rehber & Blog';
            }
            return key; // return key as fallback
        }

        // Interpolate parameters {name}
        if (params && typeof params === 'object') {
            Object.keys(params).forEach(function (p) {
                val = val.replace(new RegExp('\\{' + p + '\\}', 'g'), params[p]);
            });
        }

        return val;
    }

    /**
     * Translate a single DOM element based on its data-i18n attributes
     */
    function translateElement(el) {
        if (!el || !el.dataset) return;

        // data-i18n (textContent)
        if (el.dataset.i18n) {
            var key = el.dataset.i18n;
            if (!el.dataset.i18nOriginal) {
                el.dataset.i18nOriginal = el.textContent.trim();
            }
            var text = translate(key);
            if (text && text !== key) {
                el.textContent = text;
            } else if (currentLanguage === 'tr' && el.dataset.i18nOriginal) {
                el.textContent = el.dataset.i18nOriginal;
            }
        }

        // data-i18n-html (innerHTML)
        if (el.dataset.i18nHtml) {
            var htmlKey = el.dataset.i18nHtml;
            var html = translate(htmlKey);
            if (html && html !== htmlKey) {
                el.innerHTML = html;
            }
        }

        // data-i18n-placeholder (placeholder attribute)
        if (el.dataset.i18nPlaceholder) {
            var pKey = el.dataset.i18nPlaceholder;
            if (!el.dataset.i18nPlaceholderOriginal) {
                el.dataset.i18nPlaceholderOriginal = el.placeholder || '';
            }
            var pText = translate(pKey);
            if (pText && pText !== pKey) {
                el.placeholder = pText;
            } else if (currentLanguage === 'tr' && el.dataset.i18nPlaceholderOriginal) {
                el.placeholder = el.dataset.i18nPlaceholderOriginal;
            }
        }

        // data-i18n-title (title attribute)
        if (el.dataset.i18nTitle) {
            var tKey = el.dataset.i18nTitle;
            var tText = translate(tKey);
            if (tText && tText !== tKey) {
                el.title = tText;
            }
        }

        // data-i18n-aria (aria-label attribute)
        if (el.dataset.i18nAria) {
            var aKey = el.dataset.i18nAria;
            var aText = translate(aKey);
            if (aText && aText !== aKey) {
                el.setAttribute('aria-label', aText);
            }
        }
    }

    /**
     * Scan and translate entire DOM tree
     */
    function translateDOM(root) {
        var container = root || document;
        if (!container.querySelectorAll) return;

        // Elements with data-i18n
        var elements = container.querySelectorAll('[data-i18n], [data-i18n-html], [data-i18n-placeholder], [data-i18n-title], [data-i18n-aria]');
        for (var i = 0; i < elements.length; i++) {
            translateElement(elements[i]);
        }

        // Update html lang attribute
        document.documentElement.lang = currentLanguage;
    }

    /**
     * Change active language preference ('auto', 'tr', 'en')
     */
    function setLanguage(pref) {
        if (pref !== 'tr' && pref !== 'en' && pref !== 'auto') {
            pref = 'auto';
        }
        currentPreference = pref;
        try {
            localStorage.setItem(STORAGE_KEY, pref);
        } catch (e) {
            // ignore
        }

        var newLang = resolveEffectiveLanguage(pref);
        currentLanguage = newLang;

        // Apply immediately to html tag
        if (document && document.documentElement) {
            document.documentElement.lang = newLang;
        }

        // Translate the current page
        translateDOM(document);

        // Update Alpine store if active
        try {
            if (window.Alpine && window.Alpine.store && window.Alpine.store('i18n')) {
                window.Alpine.store('i18n').lang = newLang;
                window.Alpine.store('i18n').pref = pref;
            }
        } catch (e) {}

        // Dispatch language-changed event for Alpine and reactive components
        try {
            var evtDetail = {
                preference: pref,
                language: newLang,
                isRTL: false
            };
            window.dispatchEvent(new CustomEvent('language-changed', { detail: evtDetail }));
            window.dispatchEvent(new CustomEvent('tracemailer:language-changed', { detail: evtDetail }));
        } catch (e) {
            // ignore
        }

        return newLang;
    }

    /**
     * Register a new translation dictionary or extend existing (for future languages: de, fr, etc.)
     */
    function addLocale(langCode, dict, meta) {
        if (!langCode || !dict) return;
        dictionaries[langCode] = Object.assign(dictionaries[langCode] || {}, dict);
        if (meta) {
            supportedLanguages[langCode] = meta;
        }
    }

    // Apply immediate language to HTML tag
    document.documentElement.lang = currentLanguage;

    // Run DOM translation when document is interactive or ready
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', function () {
            translateDOM(document);
        });
    } else {
        translateDOM(document);
    }

    // MutationObserver to translate dynamically rendered elements (modals, Alpine tags, etc.)
    if (window.MutationObserver) {
        var observer = new MutationObserver(function (mutations) {
            for (var i = 0; i < mutations.length; i++) {
                var m = mutations[i];
                if (m.addedNodes && m.addedNodes.length > 0) {
                    for (var j = 0; j < m.addedNodes.length; j++) {
                        var node = m.addedNodes[j];
                        if (node.nodeType === 1) { // Element node
                            if (node.hasAttribute && (node.hasAttribute('data-i18n') || node.hasAttribute('data-i18n-placeholder'))) {
                                translateElement(node);
                            }
                            translateDOM(node);
                        }
                    }
                }
            }
        });

        // Start observing once body is available
        var attachObserver = function () {
            if (document.body) {
                observer.observe(document.body, { childList: true, subtree: true });
            } else {
                setTimeout(attachObserver, 50);
            }
        };
        attachObserver();
    }

